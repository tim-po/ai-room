"""Writes club/static/theme-club-text.css: in the «AI Room» day palette, lime is a fill, never text on white.
Every rule in the stylesheets that colours text (or an underline, an SVG stroke used as text) with the accent or
CTA gets a twin under :root[data-palette="club"][data-theme="dawn"] that uses the readable --accent-ink instead.

    python3 scripts/make_club_text.py      # rerun after changing styles that colour text with --accent/--cta
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = sorted(p for p in (ROOT / 'club/static').glob('*.css') if not p.name.startswith('theme-club')) + sorted((ROOT / 'web/src').glob('*.css'))
ACCENT = r'var\(--(?:accent|accent-hover|cta|cta-hover)\)'
PROPS = re.compile(rf'(?<![\w-])(color|text-decoration-color|-webkit-text-fill-color|caret-color)\s*:\s*{ACCENT}\s*(!important)?')
# :where() adds no specificity: each twin weighs exactly what its original weighs, so rules that beat the
# original (buttons' own text colour, say) still beat the twin.
PREFIX = ':where(:root[data-palette="club"][data-theme="dawn"])'


def rules(text):
    """(at-rule context, selector, body) for every innermost rule; comments dropped."""
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    stack, out, start = [], [], 0
    for i, ch in enumerate(text):
        if ch == '{':
            stack.append((text[start:i].strip(), i + 1))
            start = i + 1
        elif ch == '}':
            if not stack:
                start = i + 1
                continue
            head, body_start = stack.pop()
            body = text[body_start:i]
            if '{' not in body and not head.startswith('@'):
                out.append((tuple(h for h, _ in stack if h.startswith('@media') or h.startswith('@supports')), head, body))
            start = i + 1
        elif ch == ';' and not stack:
            start = i + 1
    return out


def scoped(selector):
    parts = []
    for sel in re.split(r',(?![^()]*\))', selector):
        sel = sel.strip()
        if not sel or sel.startswith(('@', 'from', 'to')) or re.fullmatch(r'[\d.%]+', sel):
            continue
        # selectors already anchored on :root keep their own conditions, then add the palette's
        if sel.startswith(':root'):
            # keep the original's own :root conditions (their weight) and add the palette's without weight
            parts.append(re.sub(r'^(:root(?:\[[^\]]*\])*)', lambda m: m.group(1) + ':where([data-palette="club"][data-theme="dawn"])', sel, count=1))
        elif sel.startswith('html'):
            parts.append('html:where([data-palette="club"][data-theme="dawn"])' + sel[4:])
        else:
            parts.append(f'{PREFIX} {sel}')
    return ','.join(parts)


blocks = []
for path in SOURCES:
    for context, selector, body in rules(path.read_text(encoding='utf-8')):
        found = PROPS.findall(body)
        if not found or ':root[data-theme=' in selector.replace('"', '') and 'dawn' not in selector:
            continue
        sel = scoped(selector)
        if not sel:
            continue
        decls = ';'.join(f'{prop}:var(--accent-ink){" " + imp if imp else ""}' for prop, imp in dict.fromkeys(found))
        rule = f'{sel}{{{decls}}}'
        for at in reversed(context):
            rule = f'{at}{{{rule}}}'
        blocks.append(f'/* {path.relative_to(ROOT)} */ {rule}')

out = ROOT / 'club/static/theme-club-text.css'
out.write_text('/* Generated by scripts/make_club_text.py: lime text becomes readable --accent-ink on «AI Room» by day. */\n'
               + '\n'.join(blocks) + '\n', encoding='utf-8')
print(len(blocks), 'rules ->', out.relative_to(ROOT))
